const DECISIONS = ["SPRAY", "BIOCONTROL", "WAIT"];

/** Animated summary of the latest day: counters + decision distribution bar. */
function MapStats({ rows, meta }) {
  const latestDay = rows.reduce((d, r) => (r.date > d ? r.date : d), rows[0].date);
  const day = rows.filter((r) => r.date === latestDay);
  const tally = Object.fromEntries(DECISIONS.map((d) => [d, day.filter((r) => r.decision === d).length]));
  const pests = day.reduce((s, r) => s + r.pest_count, 0);
  const tiles = [
    { label: "Traps mapped", value: meta?.trap_count ?? 0 },
    { label: "Trap-days", value: meta?.row_count ?? rows.length },
    { label: `Pests on ${latestDay}`, value: pests },
  ];
  return (
    <Stagger className="grid grid-cols-2 gap-4 md:grid-cols-4" stagger={0.07} delay={0.05}>
      {tiles.map((t) => (
        <StatTile key={t.label} {...t} />
      ))}
      <Item className="card col-span-2 flex flex-col justify-between gap-3 p-4! md:col-span-1">
        <span className="text-xs font-medium text-slate-500">Actions on {latestDay}</span>
        <div className="flex h-3 overflow-hidden rounded-full bg-slate-100" aria-hidden="true">
          {DECISIONS.map((d, i) => (
            <motion.div
              key={d}
              className="h-full first:rounded-l-full last:rounded-r-full"
              style={{ background: DECISION_COLORS[d], boxShadow: `0 0 12px ${DECISION_COLORS[d]}66` }}
              initial={{ width: 0 }}
              animate={{ width: `${(tally[d] / Math.max(day.length, 1)) * 100}%` }}
              transition={{ duration: 0.8, ease: EASE, delay: 0.3 + i * 0.12 }}
            />
          ))}
        </div>
        <div className="flex flex-wrap gap-x-3 gap-y-1 text-[11px] text-slate-500">
          {DECISIONS.map((d) => (
            <span key={d} className="flex items-center gap-1">
              <span aria-hidden="true" style={{ color: DECISION_COLORS[d] }}>
                {DECISION_STYLES[d].shape}
              </span>
              <AnimatedNumber value={tally[d]} /> {DECISION_STYLES[d].label.toLowerCase()}
            </span>
          ))}
        </div>
      </Item>
    </Stagger>
  );
}

function StatTile({ label, value }) {
  const tilt = useTilt(4);
  return (
    <Item className="card card-hover flex flex-col gap-2 p-4!" {...tilt}>
      <span className="text-xs font-medium text-slate-500">{label}</span>
      <span className="text-2xl font-semibold tabular-nums tracking-tight text-slate-900">
        <AnimatedNumber value={value} />
      </span>
    </Item>
  );
}
