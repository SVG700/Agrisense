/**
 * Pest Surveillance Map page.
 *
 * This module deliberately imports nothing from kepler.gl: the heavy map bundle
 * (kepler.gl + deck.gl + MapLibre + Redux) is lazy-loaded only after we know
 * the basemap is reachable and WebGL works. Otherwise the page shows a clear
 * message and still lists every trap observation.
 */
import { Component, Suspense, lazy, useCallback, useEffect, useMemo, useState } from 'react';
import { motion } from 'framer-motion';
import { CalendarDays, CloudOff, Info, Map as MapIcon, RefreshCw, TriangleAlert } from 'lucide-react';
import { api } from '../api.js';
import Badge from '../components/Badge.jsx';
import DecisionBadge from '../components/DecisionBadge.jsx';
import { DECISION_STYLES } from '../lib/decision.js';
import { AnimatedNumber, EASE, Item, Reveal, Stagger, useTilt } from '../lib/motion.jsx';
import { DECISION_COLORS, DEFAULT_STYLE_URL } from './keplerConfig.js';

const KeplerView = lazy(() => import('./KeplerView.jsx'));

const DECISION_ORDER = { SPRAY: 0, BIOCONTROL: 1, WAIT: 2 };
const DECISION_HELP = {
  SPRAY: '3-day average at or above 25 pests/day and 10+ pests per predator',
  BIOCONTROL: 'At or above 25 pests/day, but predators are keeping pace (under 10 pests each)',
  WAIT: '3-day average below 25 pests/day',
};
const REFRESH_MS = 60_000;

function hasWebGL() {
  try {
    const c = document.createElement('canvas');
    return Boolean(c.getContext('webgl2') || c.getContext('webgl'));
  } catch {
    return false;
  }
}

/** Can we reach the default (token-free) basemap style? */
async function probeBasemap(timeoutMs = 6000) {
  const ctrl = new AbortController();
  const t = setTimeout(() => ctrl.abort(), timeoutMs);
  try {
    const res = await fetch(DEFAULT_STYLE_URL, { signal: ctrl.signal, cache: 'no-store', mode: 'cors' });
    return res.ok;
  } catch {
    return false;
  } finally {
    clearTimeout(t);
  }
}

/** Catches runtime failures inside kepler.gl so the page never goes blank. */
class MapErrorBoundary extends Component {
  constructor(props) {
    super(props);
    this.state = { failed: false };
  }
  static getDerivedStateFromError() {
    return { failed: true };
  }
  componentDidCatch(err) {
    console.error('[map] kepler.gl failed to render', err);
    this.props.onError?.();
  }
  render() {
    return this.state.failed ? null : this.props.children;
  }
}

export default function PestMapPage() {
  const [days, setDays] = useState(14);
  const [data, setData] = useState(null);
  const [error, setError] = useState(null);
  const [mapState, setMapState] = useState('checking'); // checking | ready | offline | no-webgl | crashed

  const load = useCallback(async () => {
    try {
      setData(await api.mapData(days));
      setError(null);
    } catch (err) {
      setError(err.message);
    }
  }, [days]);

  useEffect(() => {
    load();
    const t = setInterval(load, REFRESH_MS);
    return () => clearInterval(t);
  }, [load]);

  const checkMap = useCallback(async () => {
    setMapState('checking');
    if (!hasWebGL()) return setMapState('no-webgl');
    setMapState((await probeBasemap()) ? 'ready' : 'offline');
  }, []);

  useEffect(() => {
    checkMap();
  }, [checkMap]);

  const rows = data?.rows ?? [];
  const meta = data?.meta;

  return (
    <div className="flex flex-col gap-6">
      {/* Header */}
      <motion.section
        initial={{ opacity: 0, y: 16 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ duration: 0.5, ease: EASE }}
        className="card flex flex-col gap-4 p-6! lg:flex-row lg:items-center lg:justify-between"
      >
        <div className="flex max-w-2xl flex-col gap-2">
          <div className="flex flex-wrap items-center gap-2">
            <span className="icon-chip h-8! w-8! rounded-lg!">
              <MapIcon className="h-4 w-4" />
            </span>
            <h2 className="text-xl font-semibold tracking-tight text-slate-900">Pest Surveillance Map</h2>
            {meta?.simulated && (
              <Badge tone="warn" className="shine" title="Some or all rows were generated by demo/seed.py or come from synthetic captures">
                Simulated data
              </Badge>
            )}
          </div>
          <p className="text-sm text-slate-500">
            One point per trap per day. Colour shows the suggested action, size shows the pest count. Press play on the
            date timeline to replay the outbreak day by day.
          </p>
          <Legend />
        </div>
        <div className="flex items-center gap-2 self-start lg:self-center">
          <label className="flex items-center gap-2 text-xs text-slate-500">
            <CalendarDays className="h-4 w-4" />
            <select value={days} onChange={(e) => setDays(Number(e.target.value))} className="field px-2 py-1.5 text-sm">
              {[7, 14, 30, 60].map((d) => (
                <option key={d} value={d}>
                  Last {d} days
                </option>
              ))}
            </select>
          </label>
          <button onClick={load} className="btn btn-ghost h-9 w-9 rounded-full p-0" aria-label="Reload map data" title="Reload map data">
            <RefreshCw className="h-4 w-4" />
          </button>
        </div>
      </motion.section>

      {error && (
        <div role="alert" className="rounded-2xl border border-rose-500/40 bg-rose-500/10 px-4 py-3 text-sm text-rose-700">
          Could not load map data: {error}
        </div>
      )}
      {meta?.warnings?.map((w) => (
        <div key={w} className="flex items-start gap-2 rounded-2xl border border-amber-500/30 bg-amber-500/5 px-4 py-2.5 text-xs text-amber-800">
          <Info className="mt-0.5 h-3.5 w-3.5 shrink-0" /> {w}
        </div>
      ))}

      {rows.length > 0 && <MapStats rows={rows} meta={meta} />}

      {/* Map */}
      <motion.section
        initial={{ opacity: 0, y: 16 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ duration: 0.5, ease: EASE, delay: 0.1 }}
        className="card relative h-[68vh] min-h-[460px] overflow-hidden p-0!"
        aria-label="Map"
      >
        {!data ? (
          <MapNotice icon={RefreshCw} spin title="Loading trap data…" />
        ) : rows.length === 0 ? (
          <MapNotice
            icon={Info}
            title="No trap observations to map yet"
            body="Give your traps coordinates (PATCH /api/device/location) or load the simulated demo: python demo/seed.py"
          />
        ) : mapState === 'ready' ? (
          <MapErrorBoundary onError={() => setMapState('crashed')}>
            <Suspense fallback={<MapNotice icon={RefreshCw} spin title="Loading map engine…" />}>
              <KeplerView rows={rows} />
            </Suspense>
          </MapErrorBoundary>
        ) : mapState === 'checking' ? (
          <MapNotice icon={RefreshCw} spin title="Connecting to the basemap…" />
        ) : (
          <MapNotice
            icon={mapState === 'offline' ? CloudOff : TriangleAlert}
            title={
              mapState === 'offline'
                ? 'The map can’t load right now'
                : mapState === 'no-webgl'
                  ? 'This browser can’t display the map'
                  : 'The map stopped working'
            }
            body={
              mapState === 'offline'
                ? 'The basemap tiles could not be reached (no internet connection, or the tile server is blocked). All trap data is still listed below.'
                : mapState === 'no-webgl'
                  ? 'WebGL is disabled or unsupported here. All trap data is still listed below.'
                  : 'The map engine hit an error. All trap data is still listed below.'
            }
            action={
              <button onClick={checkMap} className="btn btn-ghost mt-2">
                <RefreshCw className="h-4 w-4" /> Try again
              </button>
            }
          />
        )}
      </motion.section>

      <Reveal>
        <TrapTable rows={rows} meta={meta} />
      </Reveal>
    </div>
  );
}

/* -------------------------------------------------------------------------- */

function Legend() {
  return (
    <ul className="mt-1 flex flex-wrap gap-x-4 gap-y-1 text-xs text-slate-700">
      {Object.entries(DECISION_COLORS).map(([d, color]) => (
        <li key={d} className="flex items-center gap-1.5" title={DECISION_HELP[d]}>
          <span aria-hidden="true" style={{ color }}>
            {DECISION_STYLES[d].shape}
          </span>
          {DECISION_STYLES[d].label}
        </li>
      ))}
      <li className="flex items-center gap-1.5 text-slate-500">
        <span className="h-1.5 w-1.5 rounded-full bg-slate-400" />
        <span className="h-3 w-3 rounded-full bg-slate-400" /> size = pest count
      </li>
    </ul>
  );
}

function MapNotice({ icon: Icon, title, body, action, spin = false }) {
  return (
    <div className="absolute inset-0 grid place-items-center p-6 text-center" role="status">
      <div className="flex max-w-md flex-col items-center gap-2">
        <span className="icon-chip h-12! w-12! rounded-2xl!">
          <Icon className={`h-6 w-6 ${spin ? 'animate-spin' : ''}`} />
        </span>
        <p className="text-base font-semibold text-slate-900">{title}</p>
        {body && <p className="text-sm text-slate-500">{body}</p>}
        {action}
      </div>
    </div>
  );
}

/** Always-available list of observations (works with or without the map). */
function TrapTable({ rows, meta }) {
  const dates = useMemo(() => [...new Set(rows.map((r) => r.date))].sort(), [rows]);
  const [day, setDay] = useState(null);
  const selected = day && dates.includes(day) ? day : dates.at(-1);
  const dayRows = useMemo(
    () =>
      rows
        .filter((r) => r.date === selected)
        .sort((a, b) => DECISION_ORDER[a.decision] - DECISION_ORDER[b.decision] || b.pest_count - a.pest_count),
    [rows, selected]
  );
  const tally = dayRows.reduce((t, r) => ({ ...t, [r.decision]: (t[r.decision] ?? 0) + 1 }), {});

  return (
    <section className="card">
      <div className="mb-4 flex flex-wrap items-center gap-3">
        <h2 className="card-title">Trap observations</h2>
        {meta && (
          <span className="text-xs text-slate-500">
            {meta.trap_count} traps · {meta.row_count} trap-days
          </span>
        )}
        {dates.length > 0 && (
          <label className="ml-auto flex items-center gap-2 text-xs text-slate-500">
            Day
            <select value={selected} onChange={(e) => setDay(e.target.value)} className="field px-2 py-1 text-sm" aria-label="Day">
              {dates.map((d) => (
                <option key={d} value={d}>
                  {d}
                </option>
              ))}
            </select>
          </label>
        )}
      </div>

      {dayRows.length === 0 ? (
        <p className="text-sm text-slate-500">No observations.</p>
      ) : (
        <>
          <div className="mb-3 flex flex-wrap gap-2 text-xs">
            {Object.keys(DECISION_COLORS).map((d) => (
              <span key={d} className="rounded-full bg-slate-100 px-2.5 py-1 text-slate-700 ring-1 ring-slate-200">
                <span aria-hidden="true" className="mr-1.5" style={{ color: DECISION_COLORS[d] }}>
                  {DECISION_STYLES[d].shape}
                </span>
                {DECISION_STYLES[d].label}: {tally[d] ?? 0}
              </span>
            ))}
          </div>
          <div className="overflow-x-auto">
            <table className="w-full min-w-[640px] text-left text-sm">
              <thead className="text-xs uppercase tracking-wide text-slate-500">
                <tr>
                  <th className="py-2 pr-3 font-medium">Trap</th>
                  <th className="py-2 pr-3 font-medium">Decision</th>
                  <th className="py-2 pr-3 text-right font-medium">Pests</th>
                  <th className="py-2 pr-3 text-right font-medium">Natural enemies</th>
                  <th className="py-2 pr-3 font-medium">Main pest</th>
                  <th className="py-2 font-medium">Location</th>
                </tr>
              </thead>
              <Stagger as="tbody" stagger={0.02} key={selected}>
                {dayRows.map((r) => (
                  <Item as="tr" key={r.trap_id} className="row-accent border-t border-slate-200 transition-colors hover:bg-white/[0.03]">
                    <td className="py-2 pr-3 text-slate-800">
                      {r.trap_name}
                      {r.simulated && <span className="ml-2 text-[10px] uppercase tracking-wide text-amber-800">sim</span>}
                    </td>
                    <td className="py-2 pr-3">
                      <span title={r.decision_reason ?? undefined}>
                        <DecisionBadge decision={r.decision} borderline={r.borderline} size="sm" />
                      </span>
                    </td>
                    <td className="py-2 pr-3 text-right tabular-nums text-slate-800">{r.pest_count}</td>
                    <td className="py-2 pr-3 text-right tabular-nums text-slate-500">{r.predator_count}</td>
                    <td className="py-2 pr-3 text-slate-500">{r.dominant_pest ?? '—'}</td>
                    <td className="py-2 font-mono text-xs text-slate-500">
                      {r.latitude.toFixed(4)}, {r.longitude.toFixed(4)}
                    </td>
                  </Item>
                ))}
              </Stagger>
            </table>
          </div>
        </>
      )}
    </section>
  );
}

